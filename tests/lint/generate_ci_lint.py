"""Generate PR-only CI from the shared job definitions in the full workflow.

GitHub requires separate static workflow files to avoid creating skipped heavy
jobs on every PR. Keep the common jobs in one source and reject generated-file
drift in pre-commit, including when a PR changes the CI configuration itself.
"""

import argparse
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
LINT_JOBS = ("changes", "toolchain", "pre-commit", "clang-tidy", "lint-gate")
HEADER = """# Generated by tests/lint/generate_ci_lint.py from ci-full.yml; do not edit jobs here.
# Regenerate with: python tests/lint/generate_ci_lint.py --write
name: CI
run-name: >-
  CI lint PR #${{ github.event.pull_request.number }}
  @${{ github.event.pull_request.head.sha }} base:${{ github.event.pull_request.base.sha }}

on:
  pull_request:
    branches: [ "main", "integration/urma-ccu-test" ]

permissions:
  contents: read
cache-mode: read

concurrency:
  group: ci-${{ github.workflow }}-${{ github.ref }}
  cancel-in-progress: true

jobs:
"""


def render(source: str) -> str:
    """Select complete top-level job blocks without rewriting their YAML or shell."""
    jobs = source.split("\njobs:\n", 1)[1]
    matches = list(re.finditer(r"(?m)^  ([a-z][a-z0-9-]*):\n", jobs))
    blocks = {
        match[1]: jobs[match.start() : matches[index + 1].start() if index + 1 < len(matches) else len(jobs)]
        for index, match in enumerate(matches)
    }
    # The allowlist is deliberate: adding a full test never adds a skipped PR job.
    return HEADER + "".join(blocks[name] for name in LINT_JOBS).rstrip() + "\n"


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--write", action="store_true", help="Update the generated workflow")
    args = parser.parse_args()
    target = ROOT / ".github/workflows/ci.yml"
    expected = render((ROOT / ".github/workflows/ci-full.yml").read_text())
    if args.write:
        target.write_text(expected)
        return 0
    if target.read_text() != expected:
        print("CI lint workflow is out of date; run python tests/lint/generate_ci_lint.py --write")
        return 1
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
