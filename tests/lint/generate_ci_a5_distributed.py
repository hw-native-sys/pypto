"""Generate the independent comment workflow from the full CI device job."""

import argparse

from generate_ci_lint import ROOT, job_blocks

HEADER = """# Generated by tests/lint/generate_ci_a5_distributed.py; do not edit jobs here.
# Regenerate with: python tests/lint/generate_ci_a5_distributed.py --write
# Install this workflow and its controller on main: issue_comment uses the default branch.
name: CI A5 Distributed
run-name: 'A5 distributed PR #${{ github.event.issue.number }} (comment ${{ github.event.comment.id }})'

on:
  issue_comment:
    types: [created]

permissions: {}
cache-mode: read

# Independent from CI Full. Keep each request's check alive until its finalizer runs.
concurrency:
  group: ci-a5-distributed-${{ github.event.issue.number }}
  queue: max
  cancel-in-progress: false

jobs:
  changes:
    if: >-
      github.event.issue.pull_request &&
      contains(github.event.comment.body, '/ci a5-distributed')
    runs-on: ubuntu-latest
    timeout-minutes: 5
    permissions:
      contents: read
      pull-requests: read
      checks: write
    outputs:
      checkout_sha: ${{ steps.target.outputs.checkout_sha }}
      check_id: ${{ steps.target.outputs.check_id }}
    steps:
      - name: Checkout trusted command controller
        uses: actions/checkout@v4
        with:
          ref: ${{ github.workflow_sha }}
          sparse-checkout: .github/scripts
          persist-credentials: false
      - name: Validate main PR and pin its test merge
        id: target
        env:
          GH_TOKEN: ${{ github.token }}
        run: python .github/scripts/ci_a5_distributed.py prepare

"""
FOOTER = """  result:
    if: always() && needs.changes.outputs.check_id != ''
    needs: [changes, toolchain, onboard-tests-a5-distributed]
    runs-on: ubuntu-latest
    timeout-minutes: 5
    permissions:
      contents: read
      checks: write
    steps:
      - name: Checkout trusted result publisher
        uses: actions/checkout@v4
        with:
          ref: ${{ github.workflow_sha }}
          sparse-checkout: .github/scripts
          persist-credentials: false
      - name: Publish the independent PR check
        env:
          GH_TOKEN: ${{ github.token }}
          CI_NEEDS: ${{ toJSON(needs) }}
        run: python .github/scripts/ci_a5_distributed.py finish
"""


def render(source: str) -> str:
    """Reuse the exact toolchain and device steps; replace only admission gates."""
    blocks = job_blocks(source)
    toolchain = blocks["toolchain"]
    toolchain = toolchain.replace(
        "    needs: changes\n",
        "    needs: changes\n    if: needs.changes.outputs.checkout_sha != ''\n",
        1,
    )
    device = blocks["onboard-tests-a5-distributed"]
    # Full CI owns the timeout, environment, setup, tests, artifacts and cleanup.
    # The independent command deliberately has no lint or docs-only prerequisite.
    start = device.index("    permissions:\n")
    timeout = next(line for line in device.splitlines() if line.startswith("    timeout-minutes:"))
    device = (
        "  onboard-tests-a5-distributed:\n"
        f"{timeout}\n"
        "    needs: [changes, toolchain]\n"
        "    if: needs.changes.outputs.checkout_sha != ''\n" + device[start:]
    )
    # Block extraction includes comments introducing the next source job.
    # Remove only those top-level comments, keeping the job body verbatim.
    toolchain = toolchain.split("\n  #", 1)[0].rstrip() + "\n\n"
    device = device.split("\n  #", 1)[0].rstrip() + "\n\n"
    return HEADER + toolchain + device + FOOTER


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--write", action="store_true", help="Update the generated workflow")
    args = parser.parse_args()
    target = ROOT / ".github/workflows/ci-a5-distributed.yml"
    expected = render((ROOT / ".github/workflows/ci-full.yml").read_text())
    if args.write:
        target.write_text(expected)
    elif not target.exists() or target.read_text() != expected:
        print(
            "A5 distributed workflow is out of date; "
            "run python tests/lint/generate_ci_a5_distributed.py --write"
        )
        return 1
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
