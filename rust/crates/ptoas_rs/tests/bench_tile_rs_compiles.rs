//! Every `tile-rs` file in the bench corpus must compile.
//!
//! The corpus ships four representations per model folder, and until the
//! kernel-side DSL was carried here the `tile-rs` column could not be checked
//! at all. Each manifest said so in as many words -- "CORPUS ONLY ... Do not
//! read these as verified" -- which was honest and is no longer necessary.
//!
//! The first run of this gate found four files that do not compile, all of them
//! GLM-5.3 projection kernels, all with the same error: `tile_store_f32::<8, 1>`
//! applied to a `Tile<1, 1>` value, `expected 8, found 1`. They are stale output
//! of a lift defect since fixed -- a `pto.tile_buf`'s `rows`/`cols` is the extent
//! ALLOCATED against the 512-byte fractal, while `v_row`/`v_col` is the logical
//! shape, and the emitter was reading the wrong pair. The lift now REFUSES those
//! artifacts, so the files could not be regenerated even deliberately.
//!
//! That is the shape of the problem this gate exists for: a generated file
//! outlives the generator that could produce it, and nothing notices, because
//! nothing compiles the corpus.
//!
//! # Two populations, and the gate does not care
//!
//! `playground16/tile-rs/` is HAND-WRITTEN -- not one of its sixteen files
//! carries the lift's `Generated by ptoas_rs` header -- and is the corpus the
//! frontend is developed against. The other folders' files are lift output.
//! Both have to compile, for different reasons: a hand-written kernel that does
//! not compile is a bad example, and a generated one that does not compile is a
//! bug in the generator.

use std::path::{Path, PathBuf};
use std::process::Command;

const TOOLCHAIN: &str = "nightly-2025-08-04";

fn repo_root() -> PathBuf {
    Path::new(env!("CARGO_MANIFEST_DIR"))
        .join("../../..")
        .canonicalize()
        .expect("repository root")
}

fn have_toolchain() -> bool {
    Command::new("rustup")
        .args(["toolchain", "list"])
        .output()
        .map(|o| String::from_utf8_lossy(&o.stdout).contains(TOOLCHAIN))
        .unwrap_or(false)
}

/// Every `bench/*/tile-rs/*.rs`, sorted.
fn corpus() -> Vec<PathBuf> {
    let bench = repo_root().join("rust/bench");
    let mut out = Vec::new();
    let Ok(models) = std::fs::read_dir(&bench) else {
        panic!("{} is missing", bench.display());
    };
    for m in models.flatten() {
        let dir = m.path().join("tile-rs");
        if let Ok(rd) = std::fs::read_dir(&dir) {
            for e in rd.flatten() {
                let p = e.path();
                if p.extension().is_some_and(|x| x == "rs") {
                    out.push(p);
                }
            }
        }
    }
    out.sort();
    out
}

/// A scratch crate that depends on the DSL.
///
/// `[profile.dev] debug = 0` is REQUIRED, not tidiness: the DSL ICEs rustc
/// under debuginfo, and cargo ignores `[profile.*]` in a dependency's manifest,
/// so the setting has to be here in the root crate. See
/// `tests/dsl_builds_for_a_consumer.rs`.
fn stage() -> PathBuf {
    let dir = std::env::temp_dir().join(format!("bench_tile_rs_{}", std::process::id()));
    let _ = std::fs::remove_dir_all(&dir);
    std::fs::create_dir_all(dir.join("src")).expect("staging");
    let dsl = repo_root().join("rust/crates/tile_std");
    assert!(
        dsl.join("src/tile.rs").is_file(),
        "the DSL is not at {}",
        dsl.display()
    );
    std::fs::write(
        dir.join("Cargo.toml"),
        format!(
            "[package]\nname = \"bench_tile_rs_gate\"\nversion = \"0.0.0\"\nedition = \"2021\"\n\
             [lib]\npath = \"src/lib.rs\"\ntest = false\ndoctest = false\n\
             [dependencies]\ntile_std = {{ path = {:?} }}\n[workspace]\n\
             [profile.dev]\ndebug = 0\n",
            dsl.display().to_string()
        ),
    )
    .expect("manifest");
    dir
}

/// Add the tool-attribute registration a kernel crate needs.
///
/// The kernels use `#[tile(...)]` attributes, which rustc rejects without
/// `#![register_tool(tile)]` -- `error[E0433]: failed to resolve: use of
/// unresolved module or unlinked crate 'tile'`. The real lowering driver injects
/// these, so a gate that did not would blame the kernels for the harness:
/// measured, it reported 20 of 24 files broken when the true number was 4.
fn with_tool_attrs(source: &str) -> String {
    let has_feature = source
        .lines()
        .any(|l| l.trim_start().starts_with("#![feature(") && l.contains("register_tool"));
    let has_reg = source
        .lines()
        .any(|l| l.trim() == "#![register_tool(tile)]");
    let mut pre = String::new();
    if !has_feature {
        pre.push_str("#![feature(register_tool)]\n");
    }
    if !has_reg {
        pre.push_str("#![register_tool(tile)]\n");
    }
    pre + source
}

fn check(dir: &Path, source: &str) -> Result<(), String> {
    std::fs::write(dir.join("src/lib.rs"), with_tool_attrs(source)).expect("lib");
    let out = Command::new("cargo")
        .args(["check", "--message-format=short"])
        .current_dir(dir)
        .env("CARGO_TARGET_DIR", dir.join("t"))
        .env("RUSTUP_TOOLCHAIN", TOOLCHAIN)
        .env_remove("RUSTFLAGS")
        .output()
        .map_err(|e| format!("cargo could not run: {e}"))?;
    if out.status.success() {
        return Ok(());
    }
    let text = String::from_utf8_lossy(&out.stderr);
    Ok(())
        .and(Err(text
            .lines()
            .filter(|l| l.contains("error"))
            .take(3)
            .collect::<Vec<_>>()
            .join("\n")))
}

#[test]
fn every_bench_tile_rs_kernel_compiles() {
    let files = corpus();
    assert!(
        files.len() >= 20,
        "only {} tile-rs corpus file(s) found; the walk is broken, not the corpus",
        files.len()
    );
    if !have_toolchain() {
        eprintln!(
            "SKIPPED every_bench_tile_rs_kernel_compiles: {TOOLCHAIN} is not installed, so \
             {} corpus file(s) were NOT compiled. Install it with `rustup toolchain \
             install {TOOLCHAIN}`.",
            files.len()
        );
        return;
    }
    let dir = stage();
    let root = repo_root();
    let mut broken = Vec::new();
    for f in &files {
        let src = std::fs::read_to_string(f).expect("read");
        if let Err(e) = check(&dir, &src) {
            broken.push(format!(
                "  {}:\n    {}",
                f.strip_prefix(&root).unwrap_or(f).display(),
                e.replace('\n', "\n    ")
            ));
        }
    }
    let _ = std::fs::remove_dir_all(dir);
    assert!(
        broken.is_empty(),
        "{} of {} tile-rs corpus file(s) do not compile:\n{}\n\nA generated file that no \
         longer compiles usually means the generator was fixed and the file was not \
         regenerated -- check whether the lift still ACCEPTS its `.pto` before editing the \
         file by hand.",
        broken.len(),
        files.len(),
        broken.join("\n")
    );
    eprintln!("{} tile-rs corpus file(s) compile", files.len());
}

#[test]
fn a_generated_corpus_file_is_still_producible_by_the_lift() {
    // The other half. A file can compile and still be stale: if the lift now
    // refuses its `.pto`, the committed file is something the current tooling
    // cannot produce, and a reader comparing them would be comparing against a
    // ghost.
    //
    // Only files carrying the lift's own header are checked. The sixteen
    // playground kernels are hand-written and have no `.pto` ancestor in this
    // sense -- holding them to reproducibility would be asserting that a human
    // writes what the lift emits, which is the opposite of why they exist.
    let root = repo_root();
    let mut stale = Vec::new();
    for f in corpus() {
        let src = std::fs::read_to_string(&f).expect("read");
        if !src.contains("Generated by ptoas_rs") {
            continue;
        }
        let stem = f.file_stem().unwrap().to_string_lossy().to_string();
        let pto = f
            .parent()
            .and_then(|p| p.parent())
            .map(|d| d.join("pto").join(format!("{stem}.pto")));
        let Some(pto) = pto.filter(|p| p.is_file()) else {
            stale.push(format!(
                "  {}: carries the lift's header but has no `.pto` beside it",
                f.strip_prefix(&root).unwrap_or(&f).display()
            ));
            continue;
        };
        let text = std::fs::read_to_string(&pto).expect("read pto");
        if let Err(e) = ptoas_rs::convert_pto_to_rust(&text) {
            stale.push(format!(
                "  {}: the lift now REFUSES its source -- {}",
                f.strip_prefix(&root).unwrap_or(&f).display(),
                e.lines().next().unwrap_or("")
            ));
        }
    }
    assert!(
        stale.is_empty(),
        "{} generated corpus file(s) can no longer be produced from their own `.pto`:\n{}\n\n\
         Either the refusal is correct and the file should be deleted (with the manifest \
         saying why), or the refusal is a regression. Do not regenerate by editing.",
        stale.len(),
        stale.join("\n")
    );
}
