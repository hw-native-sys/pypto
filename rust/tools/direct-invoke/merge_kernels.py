#!/usr/bin/env python3
"""Concatenate emitted engine kernels into ONE translation unit.

The engine registers a single ELF and binds its kernels by SYMBOL, so artefacts meant to serve it
have to travel together. `setup.sh` builds one kernel per ELF, so the way to get several symbols
into one binary is to put them in one `.cpp`: `#include "kernel_operator.h"` once, then each kernel's
body appended.

usage: merge_kernels.py <out.cpp> <kernel.cpp> ...

VERIFIED (iteration 48): seven kernels in one unit build into a single binary carrying 14 matching
symbols (each kernel's `__global__` entry and its `_do` launcher), and kernels from it pass on device
-- `proj_w8a8_engine_1x1024_k4096_do` at wrong=0, 1.398e-07, 0.5957 ms.

ALLOW A LONG TIMEOUT WHEN BUILDING THE MERGED UNIT. The compile of a multi-kernel translation unit
takes minutes, and a 700-800 s cap kills it mid-build, producing "no result" that looks exactly like
a device fault. Two rounds were lost to that in this campaign before the raw output was read.
"""
import pathlib
import sys

def main() -> int:
    if len(sys.argv) < 3:
        print(__doc__)
        return 2
    out_path, files = sys.argv[1], sys.argv[2:]
    out = [
        "// Generated by merge_kernels.py -- do not edit.",
        '#include "kernel_operator.h"',
    ]
    for f in files:
        body = pathlib.Path(f).read_text().replace('#include "kernel_operator.h"', "")
        out.append(f"\n// ===== {pathlib.Path(f).name} =====")
        out.append(body)
    pathlib.Path(out_path).write_text("\n".join(out))
    n = sum(1 for line in "\n".join(out).splitlines() if 'extern "C"' in line)
    print(f"wrote {out_path} ({len(files)} files, {n} extern \"C\" symbols)")
    return 0

if __name__ == "__main__":
    sys.exit(main())
