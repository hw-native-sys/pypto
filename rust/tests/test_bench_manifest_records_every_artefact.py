"""The OTHER direction: an artefact on disk that no manifest string names.

Every artefact gate in this tree runs one way -- the manifest claims a path, does
a file exist there? `test_bench_manifest_artefacts.py` runs that way too. Nothing
ran this way, and this is the direction that matters for the SCORE, because
`coverage_models.py` builds a corpus's population from `manifest["kernels"]`:

    for kernel, record in manifest["kernels"].items(): ...

A kernel absent from the manifest is absent from the corpus as far as every ratio
is concerned, however many of its artefacts are committed. Over-claiming inflates
a score and is loud -- a device_check on a file that is not there. UNDER-claiming
deflates one and is silent, which is why it survived longer.

What it cost, measured 2026-11-07: Kimi K3's seven KDA projection tiles were
committed in 75af77477 on 2026-11-06, tracked, generated by the corpus's own
generator, and named NOWHERE in `bench/kimi_k3/manifest.json` -- whose `kernels`
dict held 21 and whose `totals.tile` said 21 while 28 tiles sat beside it. The
campaign scoring that corpus read T = 0.75 and attributed the gap to work not
done. The work was done. Only the bookkeeping was missing.

Two design points, both learned from getting them wrong:

  * THE SCOPES OF THE TWO DIRECTIONS DIFFER, DELIBERATELY. The forward gate reads
    `manifest["kernels"]` only, because a REMOVAL record (glm_5_3's
    `tile_rs_removed_2026_11_02.files`) names files that are correctly absent, and
    reading it as a live claim would demand restoring deleted files. This gate
    reads the WHOLE manifest, because for "is this file on record?" a mention
    anywhere is a record -- including inside a refusal note or a removal record.
    Asymmetric on purpose; symmetry here would be wrong in both directions.

  * DISCOVERY BY GLOB, NOT BY LIST. Scope was the defect the forward gate was
    written to fix (it covered `playground16` alone while four model corpora went
    ungated). A gate that enumerates the corpora it checks re-creates that defect
    the next time a corpus is added.
"""

import json
from pathlib import Path

import pytest

ROOT = Path(__file__).resolve().parents[2]
BENCH = ROOT / "rust" / "bench"

# (directory under the corpus, extension its artefacts carry, key in `totals`).
# The directory is spelled `tile-rs` and the totals key `tile_rs`; keeping both
# explicit beats deriving one from the other and being wrong on one corpus.
ARTEFACTS = (
    ("tile", ".tile", "tile"),
    ("pto", ".pto", "pto"),
    ("ascendc", ".cpp", "ascendc"),
    ("tile-rs", ".rs", "tile_rs"),
)

# `engine` is a probe corpus, not a scored model: `coverage_models.py` scores
# deepseek_v41, glm_5_3 and kimi_k3 only. Its attention-stage and w8a8 probes are
# exploratory by intent. It is NOT skipped -- an unrecorded probe is still an
# unrecorded artefact, and an exemption here is how the next corpus goes unwatched
# -- but it is reported separately so one number never mixes a scored corpus's
# uncounted work with a probe corpus's housekeeping.
SCORED_CORPORA = {"deepseek_v41", "glm_5_3", "kimi_k3"}


def _manifests():
    return sorted(BENCH.glob("*/manifest.json"))


def _every_string(node, out):
    """Every string anywhere in the manifest, at any nesting depth."""
    if isinstance(node, str):
        out.add(node)
    elif isinstance(node, dict):
        for value in node.values():
            _every_string(value, out)
    elif isinstance(node, list):
        for value in node:
            _every_string(value, out)


def _unrecorded(manifest_path):
    """Artefacts on disk whose stem no manifest string names, per directory."""
    root = manifest_path.parent
    manifest = json.loads(manifest_path.read_text(encoding="utf-8"))
    rows = set(manifest.get("kernels", {}))
    blob = set()
    _every_string(manifest, blob)
    prose = "\n".join(blob)

    missing = {}
    for sub, ext, _ in ARTEFACTS:
        directory = root / sub
        if not directory.is_dir():
            continue
        # A stem counts as recorded if it is a kernel row OR appears in any
        # manifest string -- a refusal note or a removal record is a record.
        absent = [
            p for p in sorted(directory.rglob(f"*{ext}"))
            if p.stem not in rows and p.stem not in prose
        ]
        if absent:
            missing[sub] = absent
    return missing


def _row_carries(root, row, sub, key, stem, ext):
    """Does this row carry an artefact of this representation?

    Reads the row's OWN claim first. The earlier rule was
    `(root / sub / f"{stem}{ext}").is_file()`, which assumes the file is named
    after the row -- and playground16 holds two rows that name a BLOCK variant
    (`gate_up_silu` -> `tile-rs/gate_up_silu_block.rs`, `argmax` ->
    `tile-rs/argmax_block.rs`). Both files exist and both rows carry one, so that
    rule counted 14 against the 16 this manifest has always recorded, and
    `test_bench_manifest.py::test_the_totals_are_recomputed_not_asserted` --
    which counts the claim fields -- asserted 16 at the same time. Two gates over
    one integer, disagreeing, is not two checks.

    The rows disagree among themselves about the spelling (`glm_5_3` uses
    `tile_rs`, `playground16` uses `tile-rs`), so both are accepted; the claim
    still has to RESOLVE TO A FILE, which is what keeps this a check and not a
    reading of the manifest's own prose.

    BUT ACCEPTING BOTH IS NOT PREFERRING ONE. The first version of this helper
    tried the two spellings in order and returned on the first truthy claim, and
    that tolerance hid the defect this gate exists to catch: `kimi_k3`'s
    `rope_k3_1x64` carried `"tile_rs": null` beside
    `"tile-rs": "tile-rs/rope_k3_1x64.rs"`, the helper resolved it through the
    hyphen, and the gate passed -- while every counter that matters, including the
    campaign scorer, reads `tile_rs` only and therefore saw no lift at all. A row
    can be invisible to the score and green to the gate at the same time, which is
    exactly the under-claiming one level down. So two claims that DISAGREE are a
    defect in the row, and this says so by name rather than picking a winner.
    """
    claims = {
        field: row[field]
        for field in (sub, key)
        if isinstance(row.get(field), str) and row[field]
    }
    if len(set(claims.values())) > 1:
        spelled = ", ".join(f"{f}={c!r}" for f, c in sorted(claims.items()))
        raise AssertionError(
            f"{root.name}/{stem}: the row claims its {sub} artefact under two "
            f"spellings that disagree ({spelled}). Every counter and the campaign "
            f"scorer read {key!r}, so the other spelling is invisible to them."
        )
    # A row that spells one key `null` and the other a path is the same defect seen
    # from the other side: the null is what the scorer reads.
    for field in (sub, key):
        other = key if field == sub else sub
        if isinstance(row.get(field), str) and row[field] and other in row and row[other] is None:
            raise AssertionError(
                f"{root.name}/{stem}: the row claims {field!r} = {row[field]!r} while "
                f"{other!r} is explicitly null. Every counter and the campaign scorer "
                f"read {key!r}; drop the spelling that is not read."
            )
    if claims:
        return (root / next(iter(claims.values()))).is_file()
    return (root / sub / f"{stem}{ext}").is_file()


def test_the_gate_sees_every_corpus_that_has_a_manifest():
    found = {m.parent.name for m in _manifests()}
    assert SCORED_CORPORA <= found, (
        "a scored corpus has no manifest, so this gate cannot see it: "
        f"missing {sorted(SCORED_CORPORA - found)}"
    )


@pytest.mark.parametrize(
    "manifest_path",
    [m for m in _manifests() if m.parent.name in SCORED_CORPORA],
    ids=lambda p: p.parent.name,
)
def test_a_scored_corpus_records_every_artefact_it_holds(manifest_path):
    """In a SCORED corpus, an unrecorded artefact is uncounted work or a stale file.

    Either way the manifest is wrong, and either way a ratio computed from it is
    reporting something other than the state of the tree.
    """
    missing = _unrecorded(manifest_path)
    assert not missing, (
        f"{manifest_path.parent.name}: artefacts on disk that NO manifest string "
        "names. Each is either work the score is not counting, or a file the "
        "generator no longer produces:\n"
        + "\n".join(
            f"  {sub}/: " + ", ".join(p.name for p in paths)
            for sub, paths in sorted(missing.items())
        )
    )


@pytest.mark.parametrize(
    "manifest_path",
    [m for m in _manifests() if m.parent.name not in SCORED_CORPORA],
    ids=lambda p: p.parent.name,
)
def test_an_unscored_corpus_records_every_artefact_it_holds(manifest_path):
    """Same rule, reported apart so a probe corpus never masks a scored one."""
    missing = _unrecorded(manifest_path)
    assert not missing, (
        f"{manifest_path.parent.name} (not scored): unrecorded artefacts. A probe "
        "is still an artefact; record it or remove it:\n"
        + "\n".join(
            f"  {sub}/: " + ", ".join(p.name for p in paths)
            for sub, paths in sorted(missing.items())
        )
    )


@pytest.mark.parametrize("manifest_path", _manifests(), ids=lambda p: p.parent.name)
def test_the_totals_block_agrees_with_the_rows_it_counts(manifest_path):
    """`totals.<rep>` is a second counter over the manifest. It must agree with it.

    WHAT `totals` COUNTS, established by measurement rather than assumed: the
    number of KERNEL ROWS carrying that representation -- not the number of files
    in the directory. The two differ wherever a row claims nested artefacts
    (`reshaped`, `*_chunked`, `*_aliased`), which is why `playground16` holds 20
    tile files under 16 rows and says `tile: 16`.

    I first wrote this check against the file count and it failed on all five
    corpora, including the two that every other gate passes. That was this test
    being wrong, not five manifests. The reading above holds for 15 of the 19
    (corpus, representation) pairs in the tree; the four that disagree are the
    finding, and each is a real defect:

      glm_5_3.ascendc  totals=19, rows carrying one=12  -- claims SEVEN more than
                       exist, the same seven absent `kda_*.cpp` that the forward
                       gate fails on. Two independent counters, one over claims
                       and one over files, and they corroborate each other.
      glm_5_3.pto      totals=12, rows carrying one=11  -- counts the orphan
                       `kda_conv_glm53_1x4096_k4.pto`, a width the generator no
                       longer emits.
      glm_5_3.tile_rs  totals=0, rows carrying one=2    -- not decremented when
                       `tile_rs_removed_2026_11_02` removed four of six.
      kimi_k3.tile_rs  totals=1, rows carrying one=3.

    A stored count that disagrees with what it counts is worse than no count: it
    answers the question, so nobody looks past it.
    """
    root = manifest_path.parent
    manifest = json.loads(manifest_path.read_text(encoding="utf-8"))
    totals = manifest.get("totals")
    if not isinstance(totals, dict):
        pytest.skip(f"{root.name}: no totals block to check")
    rows = manifest.get("kernels", {})

    problems = []
    for sub, ext, key in ARTEFACTS:
        claimed = totals.get(key)
        if not isinstance(claimed, int):
            continue
        directory = root / sub
        carrying = sum(1 for k in rows if _row_carries(root, rows[k], sub, key, k, ext))
        on_disk = len(list(directory.rglob(f"*{ext}"))) if directory.is_dir() else 0
        if claimed != carrying:
            problems.append(
                f"  totals.{key} = {claimed} but {carrying} kernel row(s) carry a "
                f"{sub} artefact ({on_disk} file(s) in {sub}/)"
            )
    assert not problems, (
        f"{root.name}: the totals block disagrees with the rows it counts:\n"
        + "\n".join(problems)
    )


if __name__ == "__main__":
    pytest.main([__file__, "-v"])
